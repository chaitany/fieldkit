// Bundles the sample CSV into the server code so it works on serverless hosts (no fs path guessing).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("../../../examples/acme_legacy_contacts.csv", import.meta.url));
const out = fileURLToPath(new URL("../lib/sample.generated.ts", import.meta.url));
const csv = readFileSync(src, "utf8");
writeFileSync(out, `// Generated by scripts/sync-sample.mjs. Do not edit.\nexport const SAMPLE_NAME = "acme_legacy_contacts.csv";\nexport const SAMPLE_CSV = ${JSON.stringify(csv)};\n`);
